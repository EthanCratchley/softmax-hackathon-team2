import { expect, test } from '@playwright/test';

test('desk searches aliases and groups, checks in with a bib, and isolates lesson days', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto('/desk');
  await expect(page.getByTestId('count-expected')).toHaveText('3');
  await page.getByTestId('roster-search').fill('Okafor');
  await expect(page.getByTestId('child-owen')).toBeVisible();
  await expect(page.getByTestId('child-ava')).toHaveCount(0);
  await expect(page.getByTestId('profile-owen')).toContainText('Needs information');
  await page.getByTestId('bib-owen').fill('11');
  await page.getByTestId('check-in-owen').click();
  await expect(page.getByTestId('check-in-error')).toContainText('already in use');
  await page.getByTestId('bib-owen').fill('14');
  await page.getByTestId('check-in-owen').click();
  await expect(page.getByTestId('status-owen')).toHaveText('Checked in');
  await expect(page.getByTestId('check-in-details-owen')).toContainText('Bib 14');
  await expect(page.getByTestId('check-in-details-owen')).toContainText('Jordan Ellis');
  await expect(page.getByTestId('check-in-details-owen').locator('time')).toHaveAttribute('datetime', /.+/);
  await expect(page.getByTestId('check-in-owen')).toHaveCount(0);
  await expect(page.getByTestId('count-checked-in')).toHaveText('2');
  await page.getByTestId('roster-search').fill('');
  await page.getByTestId('group-filter').selectOption('Alpine Falcons');
  await expect(page.getByTestId('child-maya')).toBeVisible();
  await expect(page.getByTestId('child-owen')).toHaveCount(0);
  await page.getByTestId('lesson-day').selectOption('2026-12-13');
  await expect(page.getByTestId('child-sam')).toBeVisible();
  await expect(page.getByTestId('count-expected')).toHaveText('1');
  await page.getByTestId('lesson-day').selectOption('2026-12-12');
  await expect(page.getByTestId('status-owen')).toHaveText('Checked in');
  await page.getByTestId('roster-search').fill('no such child');
  await expect(page.getByTestId('roster-empty')).toContainText('No children match');
  await page.getByTestId('lesson-day').selectOption('2026-12-19');
  await expect(page.getByTestId('roster-empty')).toContainText('No children scheduled');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.reload();
  await expect(page.getByTestId('status-owen')).toHaveText('Expected');
});
